let currentCategory = "All";

let currentJoke = jokes[0];


// ELEMENTS

const emojiElement =
  document.getElementById("jokeEmoji");

const questionElement =
  document.getElementById("jokeQuestion");

const answerElement =
  document.getElementById("jokeAnswer");

const scoreElement =
  document.getElementById("jokeScore");

const meterFill =
  document.getElementById("meterFill");

const anotherButton =
  document.getElementById("anotherBtn");

const copyButton =
  document.getElementById("copyBtn");

const terribleButton =
  document.getElementById("terribleBtn");

const toast =
  document.getElementById("toast");


// GET AVAILABLE JOKES

function getAvailableJokes() {

  if (currentCategory === "All") {

    return jokes;

  }

  return jokes.filter(
    joke =>
      joke.category === currentCategory
  );

}


// RANDOM JOKE

function getRandomJoke() {

  const availableJokes =
    getAvailableJokes();


  if (availableJokes.length === 0) {

    return jokes[0];

  }


  // Prevent same joke twice in a row

  if (availableJokes.length > 1) {

    let nextJoke;


    do {

      nextJoke =
        availableJokes[
          Math.floor(
            Math.random() *
            availableJokes.length
          )
        ];

    } while (
      nextJoke === currentJoke
    );


    return nextJoke;

  }


  return availableJokes[0];

}


// DISPLAY JOKE

function displayJoke(joke) {

  currentJoke = joke;


  emojiElement.textContent =
    joke.emoji;


  questionElement.textContent =
    joke.question;


  answerElement.textContent =
    joke.answer;


  scoreElement.textContent =
    `${joke.score}%`;


  meterFill.style.width =
    `${joke.score}%`;

}


// ANOTHER JOKE

anotherButton.addEventListener(
  "click",
  () => {

    displayJoke(
      getRandomJoke()
    );

  }
);


// CATEGORY BUTTONS

const categoryButtons =
  document.querySelectorAll(
    ".chip"
  );


categoryButtons.forEach(
  button => {

    button.addEventListener(
      "click",
      () => {

        currentCategory =
          button.dataset.category;


        categoryButtons.forEach(
          btn => {

            btn.classList.remove(
              "active"
            );

          }
        );


        button.classList.add(
          "active"
        );


        displayJoke(
          getRandomJoke()
        );

      }
    );

  }
);


// COPY JOKE

copyButton.addEventListener(
  "click",
  async () => {

    const text =
      `${currentJoke.question}\n${currentJoke.answer}`;


    try {

      await navigator.clipboard.writeText(
        text
      );


      showToast(
        "Copied. Your friends will hate you. 😂"
      );

    } catch {

      showToast(
        "Couldn't copy. Try again."
      );

    }

  }
);


// TERRIBLE BUTTON

terribleButton.addEventListener(
  "click",
  () => {

    const messages = [

      "I know. 😭",

      "You actually read that?",

      "Comedy has left the building.",

      "Sorry. 💀",

      "That joke needs therapy.",

      "Even I regret that one.",

      "Please don't tell anyone I made this."

    ];


    const randomMessage =
      messages[
        Math.floor(
          Math.random() *
          messages.length
        )
      ];


    showToast(
      randomMessage
    );

  }
);


// TOAST

function showToast(message) {

  toast.textContent =
    message;


  toast.classList.add(
    "show"
  );


  setTimeout(
    () => {

      toast.classList.remove(
        "show"
      );

    },
    1800
  );

}


